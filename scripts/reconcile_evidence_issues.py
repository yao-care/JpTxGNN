#!/usr/bin/env python3
"""
對帳：關閉預測清單已更新、內容已過期的證據監測 issue（2026-11-03）。

排程每次從 docs/_drugs/*.md 重產 scripts/drug_list.json，但已經開出去的 issue 沒有機制回頭關，
預測清單改過幾輪後就積壓。這支在 extract_drug_list.py 之後、檢查腳本之前執行，
對所有 open 的 auto-detected 監測 issue（label clinicaltrials 或 pubmed）逐筆檢查，符合任一條就留言並以
not_planned 關閉：
  (a) 標題沒有「→」：2026-10-16 前只按藥名開的舊版 issue
  (b) 藥已不在目前的 drug_list
  (c) issue 內文「### Predicted New Indication(s)」列的預測，一個都不在該藥目前的 predicted_indications
只有部分預測還在的不關、不留言（避免每次排程重複留言）。

跳過（不動）：有 assignee、帶 evidence-confirmed／keep 類標籤、有非 bot 的人類留言、tfda、security 標籤。

用法：
  python scripts/reconcile_evidence_issues.py            # 有 GITHUB_TOKEN 才會真的留言、關閉
  python scripts/reconcile_evidence_issues.py --dry-run  # 只讀，列出會關哪些、理由
沒有 GITHUB_TOKEN 時自動 dry-run。每次最多關 RECONCILE_MAX_CLOSE 筆（預設 50），
每筆之間至少等 RECONCILE_SLEEP 秒（預設 2，避免 GitHub 次級速率限制）。
"""

import argparse
import json
import os
import re
import sys
import time
import unicodedata
from pathlib import Path

import requests

import github_utils
from github_utils import close_issue, list_issue_comments, list_issues

DRUG_LIST_FILE = Path(__file__).parent / "drug_list.json"
MONITOR_LABELS = ["clinicaltrials", "pubmed"]
SKIP_LABELS = {"evidence-confirmed", "tfda", "security", "pinned"}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

# 留言語言跟本站監測 issue 標題一致（中文）
REASON_TEXT = {
    "no_arrow": "這是 2026-10-16 前只依藥名開立的舊版 issue，沒有對應任何預測新適應症",
    "drug_gone": "此藥目前已不在監測清單（藥物頁沒有預測新適應症或已改為轉址頁）",
    "stale": "此 issue 列的預測新適應症（{listed}）已不在此藥目前的預測清單",
}
COMMENT_TEMPLATE = (
    "🤖 自動關閉：預測清單已更新，此 issue 列的預測已不在頁面上。\n\n"
    "- 原因：{reason}\n"
    "- 此藥目前的預測新適應症：{current}\n\n"
    "若查核後仍要追蹤，請重新開啟並留言或指派負責人，之後的排程就不會再自動關閉。"
)


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", unicodedata.normalize("NFKC", text or "")).strip().casefold()


def load_drug_list() -> dict:
    with open(DRUG_LIST_FILE, "r", encoding="utf-8") as f:
        drugs = json.load(f)["drugs"]
    return {_norm(d["name"]): d for d in drugs}


def issue_drug_name(issue: dict) -> str:
    body = issue.get("body") or ""
    m = re.search(r"^### Drug Name\s*\n(.+?)\s*$", body, re.M)
    if m:
        return m.group(1).strip()
    m = github_utils.ISSUE_DRUG_RE.search(issue.get("title", ""))
    return m.group(1).strip() if m else ""


def issue_predictions(issue: dict) -> list:
    """issue 內文列的預測；內文沒有就退回標題「→」後面的部分。"""
    body = issue.get("body") or ""
    m = re.search(r"^### Predicted New Indication\(s\)\s*\n(.*?)(?=^### |\Z)", body, re.M | re.S)
    if m:
        items = [ln[2:].strip() for ln in m.group(1).splitlines() if ln.startswith("- ")]
        items = [x for x in items if x and x != "-"]
        if items:
            return items
    title = issue.get("title", "")
    if "→" in title:
        tail = title.split("→", 1)[1].replace("…", "")
        return [x.strip() for x in tail.split(";") if x.strip()]
    return []


def skip_reason(issue: dict) -> str:
    if issue.get("assignees") or issue.get("assignee"):
        return "has assignee"
    labels = {(l.get("name") or "").lower() for l in issue.get("labels", [])}
    for name in labels:
        if name in SKIP_LABELS or name.startswith("keep"):
            return f"label {name}"
    return ""


def has_human_comment(issue: dict) -> bool:
    if not issue.get("comments"):
        return False
    for c in list_issue_comments(issue["number"]):
        user = c.get("user") or {}
        if user.get("type") != "Bot" and not (user.get("login") or "").endswith("[bot]"):
            return True
    return False


def close_reason(issue: dict, drugs: dict):
    """回傳 (理由代碼, 留言用理由文字, 該藥目前預測)；不該關回傳 None。"""
    title = issue.get("title", "")
    if "→" not in title:
        drug = drugs.get(_norm(issue_drug_name(issue)))
        return "no_arrow", REASON_TEXT["no_arrow"], (drug or {}).get("predicted_indications", [])
    drug = drugs.get(_norm(issue_drug_name(issue)))
    if not drug:
        return "drug_gone", REASON_TEXT["drug_gone"], []
    current = drug.get("predicted_indications") or []
    listed = issue_predictions(issue)
    current_norm = {_norm(x) for x in current}
    if listed and not any(_norm(x) in current_norm for x in listed):
        return "stale", REASON_TEXT["stale"].format(listed="; ".join(listed)), current
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true", help="只讀，不留言、不關閉")
    ap.add_argument("--max-close", type=int, default=int(os.environ.get("RECONCILE_MAX_CLOSE", "50")))
    ap.add_argument("--sleep", type=float, default=max(2.0, float(os.environ.get("RECONCILE_SLEEP", "2"))))
    args = ap.parse_args()

    dry_run = args.dry_run or not github_utils.GITHUB_TOKEN
    print(f"Reconcile evidence issues in {github_utils.GITHUB_REPO}"
          f" ({'DRY RUN' if dry_run else 'LIVE'}, max close {args.max_close})")

    drugs = load_drug_list()
    try:
        issues = {}
        for label in MONITOR_LABELS:
            for issue in list_issues({"state": "open", "labels": f"auto-detected,{label}"}):
                issues[issue["number"]] = issue
    except requests.RequestException as e:
        print(f"Error listing issues: {e}")
        return 1

    print(f"Open monitor issues: {len(issues)}; drugs in list: {len(drugs)}")
    to_close, skipped, kept = [], [], 0
    for number in sorted(issues):
        issue = issues[number]
        reason = close_reason(issue, drugs)
        if not reason:
            kept += 1
            continue
        why_skip = skip_reason(issue)
        if not why_skip:
            try:
                if has_human_comment(issue):
                    why_skip = "human comment"
            except requests.RequestException as e:
                why_skip = f"comments unreadable ({e})"
        if why_skip:
            skipped.append((number, why_skip))
            continue
        to_close.append((issue, reason))

    counts = {}
    for _, (code, _, _) in to_close:
        counts[code] = counts.get(code, 0) + 1
    print(f"Keep (predictions still current): {kept}")
    print(f"Skip (protected): {len(skipped)} {skipped[:20]}")
    print(f"Would close: {len(to_close)} {counts}")

    closed = 0
    for issue, (code, reason_text, current) in to_close:
        if closed >= args.max_close:
            print(f"Reached max close ({args.max_close}); rest left for the next run")
            break
        print(f"  #{issue['number']} [{code}] {issue['title']}")
        if dry_run:
            closed += 1
            continue
        comment = COMMENT_TEMPLATE.format(
            reason=reason_text,
            current="; ".join(current) if current else "（無）",
        ) + FOOTER
        if close_issue(issue["number"], comment, state_reason="not_planned"):
            closed += 1
        time.sleep(args.sleep)

    print(f"{'Would close' if dry_run else 'Closed'} {closed} issue(s) this run")
    return 0


if __name__ == "__main__":
    sys.exit(main())
