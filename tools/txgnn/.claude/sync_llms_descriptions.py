import json, re, sys
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
LINE = re.compile(r"^- `(/[^`]*)` (.+?) — (.+)$")
LABEL = re.compile(r"^(\s*[-*]\s*.+?\s*\()(L[1-5]|N/A)(\)\s*:\s*)(https?://\S+?)(\s*)$")


def yaml_str(v):
    v = v.strip()
    if v.startswith('"') and v.endswith('"'):
        try:
            return json.loads(v)
        except ValueError:
            return v[1:-1]
    if v.startswith("'") and v.endswith("'"):
        return v[1:-1].replace("''", "'")
    return v


def pages(proj: Path) -> dict:
    out = {}
    for f in list((proj / "docs").glob("*.md")) + list((proj / "docs").glob("*/index.md")):
        t = f.read_text(encoding="utf-8", errors="replace")
        m = re.match(r"(?:﻿)?---\r?\n(.*?)\r?\n---", t, re.S)
        if not m:
            continue
        fm = m.group(1)
        g = lambda k: (re.search(rf"^{k}:\s*(.+)$", fm, re.M) or [None, None])[1]
        pl = g("permalink")
        if not pl:
            pl = "/" if f.name == "index.md" and f.parent.name == "docs" else None
        if pl and g("description"):
            out[yaml_str(pl)] = (yaml_str(g("title") or ""), yaml_str(g("description")))
    return out


def drug_pages(proj: Path):
    """{藥物頁網址路徑: (evidence_level, 狀態)}；狀態＝""（可收錄）、"轉址"、"noindex"。網址照 _config.yml 的 drugs permalink 樣板。"""
    cfg = (proj / "docs/_config.yml").read_text(encoding="utf-8", errors="replace")
    m = re.search(r"^  drugs:\s*\n((?:    .*\n)+)", cfg, re.M)
    pm = re.search(r"permalink:\s*(\S+)", m.group(1)) if m else None
    pat = yaml_str(pm.group(1)) if pm else "/drugs/:name/"
    out = {}
    for f in (proj / "docs/_drugs").glob("*.md"):
        t = f.read_text(encoding="utf-8", errors="replace")
        fm = re.match(r"(?:\ufeff)?---\r?\n(.*?)\r?\n---", t, re.S)
        fm = fm.group(1) if fm else ""
        g = lambda k: yaml_str((re.search(rf"^{k}:[ \t]*(.*?)[ \t]*\r?$", fm, re.M) or [None, ""])[1])
        url = g("permalink") or re.sub(r":(name|slug|title)\b", re.sub(r"[\W_]+", "-", g("slug") or f.stem).strip("-").lower(), pat)
        state = ("轉址" if g("layout") == "id_redirect" or 'http-equiv="refresh"' in t or g("redirect_to")
                 else "noindex" if g("noindex").lower() == "true" else "")
        out[url.rstrip("/") + "/"] = (g("evidence_level"), state)
    return pat.split(":")[0], out


def sync_labels(proj: Path, lines: list, name: str) -> int:
    """範例藥物行的 (Lx) 標籤對齊藥物頁 evidence_level；回傳改了幾行。"""
    cname = proj / "docs/CNAME"
    if not cname.exists() or not (proj / "docs/_drugs").is_dir():
        return 0
    site = "https://" + cname.read_text(encoding="utf-8").strip()
    prefix, pages_ = drug_pages(proj)
    n = 0
    for i, l in enumerate(lines):
        m = LABEL.match(l)
        if not m or not m.group(4).startswith(site):
            continue
        path = (m.group(4)[len(site):].split("#")[0].split("?")[0] or "/").rstrip("/") + "/"
        if not path.startswith(prefix):
            continue  # 不是藥物頁（如 /evidence-low/ 的等級說明行）
        lv, state = pages_.get(path, (None, "不存在"))
        if state:
            print(f"  ⚠ {proj.name}/docs/{name}：{l.strip()} 指到{state}的頁，請換一個藥")
        elif re.fullmatch(r"L[1-5]|N/A", lv or "") and lv != m.group(2):
            lines[i] = m.group(1) + lv + m.group(3) + m.group(4) + m.group(5)
            n += 1
        elif not re.fullmatch(r"L[1-5]|N/A", lv or ""):
            print(f"  ⚠ {proj.name}/docs/{name}：{l.strip()} 的頁面 evidence_level 是「{lv}」，無法對應標籤")
    return n


