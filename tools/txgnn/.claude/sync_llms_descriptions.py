def site_data_table() -> dict:
    out = {}
    for l in SITE_DATA_TSV.read_text(encoding="utf-8").splitlines():
        if not l.strip() or l.startswith("#"):
            continue
        site, lang, dataset, *_ = l.split("\t")
        out[site] = (lang, dataset)
    return out


def na_label(proj: Path) -> str:
    """N/A 藥物頁 parent 的標題（該站自己的「僅已知用途」列表頁名稱）；沒有 N/A 頁就回空字串。"""
    cnt = {}
    for f in (proj / "docs/_drugs").glob("*.md"):
        fm = re.match(r"(?:\ufeff)?---\r?\n(.*?)\r?\n---", f.read_text(encoding="utf-8", errors="replace"), re.S)
        fm = fm.group(1) if fm else ""
        g = lambda k: yaml_str((re.search(rf"^{k}:[ \t]*(.*?)[ \t]*\r?$", fm, re.M) or [None, ""])[1])
        if g("evidence_level") == "N/A" and g("parent"):
            cnt[g("parent")] = cnt.get(g("parent"), 0) + 1
    return max(sorted(cnt), key=cnt.get) if cnt else ""


def site_data_lines(proj: Path, name: str, table: dict):
    """本站資料區塊的各行（不含換行）；資料不齊就回 None 並印 ⚠。"""
    if name not in table:
        print(f"  ⚠ {name} 不在 {SITE_DATA_TSV.name}，不寫本站資料區塊")
        return None
    lang, dataset = table[name]
    stats_f = proj / "docs/_data/drug_stats.json"
    if lang not in SD_TEXT or not stats_f.exists():
        print(f"  ⚠ {name}：語言 {lang} 沒有區塊文字或缺 drug_stats.json，不寫本站資料區塊")
        return None
    st = json.loads(stats_f.read_text(encoding="utf-8"))
    total, lc = int(st["total_drugs"]), st.get("level_counts") or {}
    counts = [(f"L{i}", int(lc.get(f"L{i}", 0))) for i in range(1, 6)]
    counts.append(("N/A", total - sum(v for _, v in counts)))
    head, ds_label, lv_label = SD_TEXT[lang]
    na = na_label(proj)
    cjk = lang in ("zh-Hant", "ja")  # 中日文站的 llms 用全形冒號與括號
    colon = "：" if cjk else ": "
    dist = " · ".join(f"{k} {v}" for k, v in counts)
    if na:
        dist += f"（N/A＝{na}）" if cjk else f" (N/A = {na})"
    return [SD_BEGIN, f"## {head}", "", f"- {ds_label}{colon}{dataset}", f"- {lv_label.format(n=total)}{colon}{dist}", SD_END]


def sync_site_data(lines: list, block: list) -> list:
    """把本站資料區塊放進 lines：已有就原位整段換掉（重複的整段刪掉），沒有就插在第一個談 L1 的章節之後。"""
    text = "\n".join(lines)
    found = list(SD_BLOCK.finditer(text))
    if found:
        for m in reversed(found[1:]):  # 重複的區塊連同後面的空行一起刪
            b = m.end()
            while text[b:b + 1] == "\n":
                b += 1
            text = text[:m.start()] + text[b:]
        m = found[0]
        return (text[:m.start()] + "\n".join(block) + text[m.end():]).split("\n")
    heads = [i for i, l in enumerate(lines) if l.startswith("## ")]
    at = None
    for j, h in enumerate(heads):
        if j + 1 < len(heads) and any(re.search(r"\bL1\b", l) for l in lines[h:heads[j + 1]]):
            at = heads[j + 1]  # 下一個章節標題之前
            break
    if at is None:  # 找不到談 L1 的章節：接在檔尾（保留原本的結尾空行）
        at = len(lines)
        while at > 0 and lines[at - 1] == "":
            at -= 1
        return lines[:at] + [""] + block + lines[at:]
    pre = [""] if at > 0 and lines[at - 1] != "" else []
    return lines[:at] + pre + block + [""] + lines[at:]


def main(argv):
    sys.path.insert(0, str(BASE / ".claude"))
    import site_registry
    sites = argv or site_registry.all_projects()
    table = site_data_table()
    for s in sites:
        proj = Path(s).resolve() if "/" in s else BASE / s
        s = proj.name
        pg = pages(proj)
        n = labels = sd = 0
        for name in ("llms.txt", "llms-full.txt"):
            f = proj / "docs" / name
            if not f.exists():
                continue
            b = f.read_bytes()
            nl = "\r\n" if b"\r\n" in b else "\n"
            lines = b.decode("utf-8").split(nl)
            for i, l in enumerate(lines):
                m = LINE.match(l)
                if m and m.group(1) in pg:
                    title, desc = pg[m.group(1)]
                    new = f"- `{m.group(1)}` {title or m.group(2)} — {desc}"
                    if new != l:
                        lines[i] = new
                        n += 1
            nlab = sync_labels(proj, lines, name)
            n += nlab
            labels += nlab
            block = site_data_lines(proj, s, table)
            if block:
                new_lines = sync_site_data(lines, block)
                if new_lines != lines:
                    n += 1
                    sd += 1
                    lines = new_lines
            out = nl.join(lines).encode("utf-8")
            if out != b:
                f.write_bytes(out)
        print(f"{s}: {n} 處更新" + (f"（含範例藥物等級標籤 {labels} 行）" if labels else "")
              + (f"（含本站資料區塊 {sd} 個檔）" if sd else ""))


if __name__ == "__main__":
    main(sys.argv[1:])
